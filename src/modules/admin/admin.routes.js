import { Router } from 'express';
import { requireAdmin } from '../auth/auth.middleware.js';
import * as c from './admin.controller.js';
const router = Router();
router.use(requireAdmin);
router.get('/orders/filters', c.filters);
router.get('/orders', c.listOrders);
router.get('/orders/:id', c.detail);
router.patch('/orders/:id/status', c.status);
router.post('/orders/:id/shipment', c.shipment);
router.patch('/orders/:id/shipment', c.shipment);
router.patch('/orders/:id/shipment/status', c.shipment);
router.post('/orders/:id/notes', c.notes);
router.get('/orders/:id/notes', c.detail);
router.post('/orders/:id/cancel', c.cancel);
router.get('/orders/:id/invoice', c.invoice);
router.post('/orders/:id/refunds', c.initiateRefund);
router.get('/orders/:id/refunds/:refundId', c.reconcileRefund);
router.get('/settings', c.settings);
router.get('/settings/invoice', c.invoiceSettings);
router.get('/settings/shipping', c.shippingSettings);
router.get('/settings/packing', c.packingSettings);
router.get('/settings/order-policies', c.orderPolicies);
router.get('/settings/metadata', c.metadata);
router.put('/settings/invoice', c.saveInvoice);
router.put('/settings/order-policies', c.saveOrderPolicies);
router.post('/settings/charges', c.saveCharge);
router.post('/settings/shipping', (req, res, next) => { req.params.type = 'shipping'; next(); }, c.saveCharge);
router.post('/settings/packing', (req, res, next) => { req.params.type = 'packing'; next(); }, c.saveCharge);
router.patch('/settings/charges/:id', c.saveCharge);
router.patch('/settings/shipping/:id', (req, res, next) => { req.params.type = 'shipping'; next(); }, c.saveCharge);
router.patch('/settings/packing/:id', (req, res, next) => { req.params.type = 'packing'; next(); }, c.saveCharge);
router.delete('/settings/charges/:id', c.archiveCharge);
router.delete('/settings/shipping/:id', c.archiveCharge);
router.delete('/settings/packing/:id', c.archiveCharge);
export default router;
