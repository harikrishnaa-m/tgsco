import { Router } from 'express';
import { requireAdmin, requireUser } from '../auth/auth.middleware.js';
import * as c from './returns.controller.js';
const router = Router();
router.post('/admin/orders/:id/returns', requireAdmin, c.adminList);
router.get('/admin/orders/:id/returns', requireAdmin, c.adminList);
router.get('/admin/returns', requireAdmin, c.adminList);
router.get('/admin/returns/filters', requireAdmin, c.adminFilters);
router.get('/admin/returns/:returnId', requireAdmin, c.adminDetail);
router.patch('/admin/returns/:returnId/status', requireAdmin, c.adminStatus);
router.post('/refund-methods', requireUser, c.createRefundMethod);
router.get('/refund-methods', requireUser, c.listRefundMethods);
router.get('/refund-methods/:refundMethodId', requireUser, c.getRefundMethod);
router.patch('/refund-methods/:refundMethodId', requireUser, c.updateRefundMethod);
router.delete('/refund-methods/:refundMethodId', requireUser, c.deleteRefundMethod);
router.post('/orders/:id/returns', requireUser, c.create);
router.get('/orders/:id/returns', requireUser, c.list);
router.get('/returns', requireUser, c.list);
router.get('/returns/filters', requireUser, c.adminFilters);
router.get('/returns/:returnId', requireUser, c.detail);
router.post('/returns/:returnId/cancel', requireUser, c.cancel);
export default router;
